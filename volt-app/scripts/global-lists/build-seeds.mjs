#!/usr/bin/env node
/* ============================================================================
 *  REBUILD THE SHIPPED GLOBAL LIST SEEDS (src/data/globalLists/*.seed.ts).
 *
 *    cd volt-app/scripts/global-lists
 *    npm i --no-save timezones.json world-countries libphonenumber-js
 *    node build-seeds.mjs
 *
 *  Sources (pinned by whatever version npm installs; the version is written
 *  into each seed's header):
 *    timezones.json     MIT     the timezone list, in the exact shape Volt
 *                               stores (abbr, offset, isdst, text, utc[])
 *    world-countries    ODbL    short and official country names, ISO 3166-1
 *                               alpha-2, alpha-3 and numeric codes
 *    libphonenumber-js  MIT     international calling codes
 *
 *  Raising SEED_VERSION in a seed makes the next boot ADD shipped items that a
 *  database does not have yet (by code). It never overwrites an item a System
 *  Admin edited; "Restore shipped values" in the console does that on request.
 * ========================================================================== */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '../../src/data/globalLists');
const ver = (p) => require(`${p}/package.json`).version;

const slug = (s) => s.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// ---- timezones -------------------------------------------------------------
const tz = require('timezones.json');
const used = new Set();
const tzItems = tz.map((t) => {
  // Stable code: the zone's name, made unique where the source repeats one
  // ("GMT Standard Time" is both "Edinburgh, London" and "Dublin, Lisbon").
  let code = slug(t.value);
  if (used.has(code)) code = slug(`${t.value} ${t.text.replace(/^\(UTC[^)]*\)\s*/, '')}`);
  used.add(code);
  const offset = String(t.offset);
  return { code, value: { en_US: `${t.value} (${offset})`, abbr: t.abbr, offset, isdst: !!t.isdst, text: t.text, utc: t.utc ?? [] } };
});

// ---- countries -------------------------------------------------------------
const wc = require('world-countries');
const lp = require('libphonenumber-js');
function phone(c) {
  try { const n = lp.getCountryCallingCode(c.cca2); if (n) return `+${n}`; } catch { /* not in libphonenumber */ }
  // A few territories libphonenumber has no metadata for. Use the source's
  // dialling prefix when it names exactly one, except UM (US Minor Outlying
  // Islands), which world-countries gives as +268 (that is Eswatini's code).
  if (c.cca2 !== 'UM' && c.idd?.root && c.idd.suffixes?.length === 1) return `${c.idd.root}${c.idd.suffixes[0]}`;
  return null;
}
const countryItems = wc
  .map((c) => ({
    code: c.cca2,
    value: {
      name: c.name.common, officialName: c.name.official,
      alpha2: c.cca2, alpha3: c.cca3, ...(c.ccn3 ? { numeric: c.ccn3 } : {}),
      ...(phone(c) ? { phoneCode: phone(c) } : {}),
    },
  }))
  .sort((a, b) => a.value.name.localeCompare(b.value.name, 'en'));

const header = (what, sources) => `// ============================================================================
//  GENERATED by scripts/global-lists/build-seeds.mjs. Do not edit by hand:
//  change the list in System Admin > Global lists, or rebuild this file.
//  ${what}
//  Sources: ${sources}
// ============================================================================
import type { SeedItem } from '../../services/globalLists';
`;

const emit = (file, what, sources, version, items) => writeFileSync(join(outDir, file),
  `${header(what, sources)}
export const SEED_VERSION = ${version};

export const ITEMS: SeedItem[] = [
${items.map((i, n) => `  ${JSON.stringify({ ...i, position: n })},`).join('\n')}
];
`);

emit('timezones.seed.ts', `${tzItems.length} timezones.`, `timezones.json ${ver('timezones.json')} (MIT).`, 1, tzItems);
emit('countries.seed.ts', `${countryItems.length} countries and territories (ISO 3166-1).`,
  `world-countries ${ver('world-countries')} (ODbL 1.0, https://github.com/mledoze/countries), libphonenumber-js ${ver('libphonenumber-js')} (MIT).`, 1, countryItems);
console.log(`timezones ${tzItems.length}, countries ${countryItems.length} -> ${outDir}`);
