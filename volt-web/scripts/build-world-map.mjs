// Build the world map the Rights demand report draws (build queue P2-4).
//
// The console draws countries as plain SVG paths, projected once here, so the
// page needs no map library and no network: the map is a ~90 KB module loaded
// only when the report opens. Countries come from Natural Earth's 1:110m set
// (world-atlas, public domain), keyed by ISO 3166-1 alpha-2, which is what
// the play gate and the edge record. Countries too small for 1:110m (for
// example Singapore, Hong Kong, Malta) have no shape; the report's table
// lists them all the same.
//
// Regenerate (only when changing the projection or the source):
//   cd volt-web && npm i --no-save world-atlas@2 topojson-client@3 d3-geo@3 i18n-iso-countries@7
//   node scripts/build-world-map.mjs   (writes src/lib/worldMap.data.ts)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { feature } from 'topojson-client';
import { geoNaturalEarth1, geoPath } from 'd3-geo';
import countries from 'i18n-iso-countries';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/countries-110m.json'), 'utf8'));
const all = feature(topo, topo.objects.countries).features;

// Natural Earth gives a few places no numeric code; these are the ones with an
// alpha-2 in use by CDNs and IP databases.
const NAMED = { Kosovo: 'XK', 'N. Cyprus': 'CY', Somaliland: 'SO' };
const iso2 = (f) => (f.id ? countries.numericToAlpha2(f.id) : NAMED[f.properties.name]) || null;

// Antarctica is left off: nobody watches from it and it takes a fifth of the height.
const feats = all.filter((f) => iso2(f) && iso2(f) !== 'AQ');
const W = 960;
const proj = geoNaturalEarth1().fitWidth(W, { type: 'FeatureCollection', features: feats });
const path = geoPath(proj).digits(1);
const [[, y0], [, y1]] = geoPath(proj).bounds({ type: 'FeatureCollection', features: feats });
const H = Math.ceil(y1 - Math.min(0, y0));

const shapes = {};
for (const f of feats) {
  const k = iso2(f);
  const d = path(f);
  if (!d) continue;
  shapes[k] = shapes[k] ? shapes[k] + d : d; // N. Cyprus joins Cyprus, Somaliland Somalia
}
const keys = Object.keys(shapes).sort();
const body = keys.map((k) => `  ${k}: ${JSON.stringify(shapes[k])},`).join('\n');
const out = `// Generated by scripts/build-world-map.mjs from Natural Earth 1:110m (world-atlas, public domain).
// Natural Earth projection, ${W} x ${H}, Antarctica left off. Do not edit by hand.
export const WORLD_W = ${W}
export const WORLD_H = ${H}
/** Country outlines as SVG path data, keyed by ISO 3166-1 alpha-2. */
export const WORLD_SHAPES: Record<string, string> = {
${body}
}
`;
writeFileSync(join(here, '../src/lib/worldMap.data.ts'), out);
console.log(`${keys.length} countries, ${W} x ${H}, ${(out.length / 1024).toFixed(1)} KB`);
